export type MessageKey = keyof typeof sr;

export const messages: Record<Locale, Record<MessageKey, string>> = { sr, en };

export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let s = messages[locale][key] ?? messages.sr[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function mealLabelKey(slot: string): MessageKey {
  return `meal.${slot}` as MessageKey;
}

export function activityLabelKey(level: string): MessageKey {
  return `activity.${level}` as MessageKey;
}

export function exportPeriodKey(period: "7d" | "14d" | "30d" | "goal" | "all"): MessageKey {
  return `export.period.${period}` as MessageKey;
}
